"""Render a validated BundleRequest into bundle files. Rendering is pure and deterministic."""

from __future__ import annotations

import json
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

import yaml
from jinja2 import Environment, FileSystemLoader, StrictUndefined

from src.generators.cluster_config_builder import build_cluster_spec
from src.generators.patterns import PATTERNS
from src.generators.spark_job_builder import build_asset_bundle, build_job_spec
from src.models.bundle_request import BundleRequest, Pattern
from src.validators.request_validator import LTS_RUNTIMES, MIN_RUNTIME

TEMPLATES_DIR = Path(__file__).resolve().parent.parent / "templates"
BUNDLE_FILES = (
    "bundle.yml", "pipeline.sql", "cluster_config.yml", "job_config.yml", "databricks.yml",
    "request.json",
)

_env = Environment(
    loader=FileSystemLoader(TEMPLATES_DIR),
    undefined=StrictUndefined,  # a missing variable is a bug, never an empty string
    trim_blocks=True,
    lstrip_blocks=True,
    keep_trailing_newline=True,
    autoescape=False,
)


class BundleExistsError(FileExistsError):
    pass


def _yaml(header: str, data: dict[str, Any]) -> str:
    body = yaml.safe_dump(data, sort_keys=False, default_flow_style=False, allow_unicode=True)
    return f"# {header}\n# Generated by Databricks Agent. Regenerate from request.json.\n{body}"


def _bundle_metadata(r: BundleRequest) -> dict[str, Any]:
    p = r.parameters
    info = PATTERNS[r.pattern]
    transformations = ["lineage columns"]
    if r.pattern is Pattern.INCREMENTAL_LOAD:
        transformations += ["watermark filter", "dedupe by primary key", "merge upsert"]
    else:
        transformations += ["atomic replace"]
    return {
        "name": r.bundle_name,
        "version": r.version,
        "pattern": r.pattern.value,
        "created_by": r.created_by,
        "created_at": r.created_at.isoformat() if r.created_at else None,
        "description": r.description.strip(),
        "supported_runtimes": [f"{a}.{b}" for a, b in sorted(LTS_RUNTIMES) if (a, b) >= MIN_RUNTIME],
        "lineage": {
            "source": {"path": p.source_path, "format": p.source_format},
            "transformations": transformations,
            "destination": {"type": "unity_catalog", "table": r.target_table},
            "audit_table": r.audit_table,
        },
        "data_quality": list(info.practices),
        "parameters": p.model_dump(exclude_none=True),
    }


def render_bundle(r: BundleRequest) -> dict[str, str]:
    """Return {filename: content} for the bundle. Same request -> byte-identical output."""
    # Pin created_at so the stored request and bundle.yml always agree.
    r = r.model_copy(update={"created_at": r.created_at or datetime.now(UTC).date()})
    sql = _env.get_template(PATTERNS[r.pattern].template).render(r=r)
    return {
        "bundle.yml": _yaml(f"Bundle metadata: {r.bundle_name}", _bundle_metadata(r)),
        "pipeline.sql": sql,
        "cluster_config.yml": _yaml(f"Job cluster spec: {r.bundle_name}", build_cluster_spec(r)),
        "job_config.yml": _yaml(f"Databricks Jobs API 2.1 definition: {r.bundle_name}",
                                build_job_spec(r)),
        "databricks.yml": _yaml(f"Databricks Asset Bundle: {r.bundle_name}", build_asset_bundle(r)),
        "request.json": json.dumps(r.model_dump(mode="json"), indent=2) + "\n",
    }


def write_bundle(r: BundleRequest, output_dir: Path, force: bool = False) -> Path:
    target = output_dir / r.bundle_name
    if target.exists() and not force:
        raise BundleExistsError(f"{target} already exists (use --force to regenerate)")
    files = render_bundle(r)
    target.mkdir(parents=True, exist_ok=True)
    for name, content in files.items():
        (target / name).write_text(content)
    return target
